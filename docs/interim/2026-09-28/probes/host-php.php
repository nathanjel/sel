<?php
require_once __DIR__ . '/../wt2/php/src/bootstrap.php';
use Sel\Sel; use Sel\Value;
function T($n, $f) { try { $r = $f(); $o = 'OK ' . ($r instanceof Value ? substr($r->dump(), 0, 80) : substr(json_encode($r), 0, 80)); } catch (\Throwable $e) { $o = 'ERR ' . (method_exists($e, 'getSelCode') ? $e->getSelCode() : (property_exists($e, 'code') && is_string($e->code ?? null) ? $e->code : get_class($e))) . ' ' . substr($e->getMessage(), 0, 70); } printf("%-36s %s\n", $n, $o); }
$bad = "a\xff";
T('text(bad) [control]', fn() => Value::text($bad));
T('fromNative([bad=>1]) [control]', fn() => Value::fromNative([$bad => 1]));
T('none()->set(bad) [control]', fn() => Value::none()->set($bad, Value::text('1')));
T('shaped([bad],[1])', fn() => Value::shaped([$bad], [Value::text('1')]));
T('record([bad],[1])', fn() => Value::record([$bad], [Value::text('1')]));
T('fromEntries([[bad,1]])', fn() => Value::fromEntries([[$bad, Value::text('1')]]));
T('list([1],[bad]) keys', fn() => Value::list([Value::text('1')], [$bad]));
T('fromNativeRows([[bad=>1]])', fn() => Value::fromNativeRows([[$bad => 1]]));
T('fromNativeRows([[bad=>1]]) → INDEXES', fn() => Sel::compile('MAP(X, INDEXES(_))')->run(['X' => Value::fromNativeRows([[$bad => 1]])]));
T('fromNativeRows([[a=>1],[bad=>1]])', fn() => Value::fromNativeRows([['a' => 1], [$bad => 1]]));
T('fromNativeRows([[a=>bad]]) value', fn() => Value::fromNativeRows([['a' => $bad]]));
T('shaped count mismatch', fn() => Value::shaped(['a'], [Value::text('1'), Value::text('2')]));
T('shaped duplicate keys', fn() => Value::shaped(['a', 'a'], [Value::text('1'), Value::text('2')]));
T('record duplicate keys', fn() => Value::record(['a', 'a'], [Value::text('1'), Value::text('2')]));
T('list keys count mismatch', fn() => Value::list([Value::text('1')], ['1', '2']));
T('list duplicate keys', fn() => Value::list([Value::text('1'), Value::text('2')], ['5', '5']));
T('list non-numeric keys', fn() => Value::list([Value::text('1')], ['x']));
$D = ['neg' => false, 'digits' => '1', 'scale' => 1000001];
T('num(Dec scale 1000001)', fn() => Value::num($D));
T('num(Dec digits 1000001 int)', fn() => Value::num(['neg' => false, 'digits' => str_repeat('1', 1000001), 'scale' => 0]));
T('num(Dec malformed digits "x")', fn() => Value::num(['neg' => false, 'digits' => 'x', 'scale' => 0]));
T('num(Dec negative scale)', fn() => Value::num(['neg' => false, 'digits' => '1', 'scale' => -1]));
T('num(Dec leading zeros "007")', fn() => Value::num(['neg' => false, 'digits' => '007', 'scale' => 0]));
T('num(Dec neg zero)', fn() => Value::num(['neg' => true, 'digits' => '0', 'scale' => 0]));
T('num("1"x1000001)', fn() => Value::num(str_repeat('1', 1000001)));
T('fromNative(float 1e308)', fn() => strlen(Value::fromNative(1e308)->dump()));
T('fromNative(PHP_INT_MAX)', fn() => Value::fromNative(PHP_INT_MAX));
T('bin(any string)', fn() => Value::bin("\x00\xff"));
