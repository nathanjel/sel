DROP TABLE IF EXISTS order_lines, orders, customers, products, categories;
CREATE TABLE categories (category_id INTEGER PRIMARY KEY, category TEXT NOT NULL UNIQUE);
CREATE TABLE products (product_id INTEGER PRIMARY KEY, sku TEXT NOT NULL UNIQUE, title TEXT NOT NULL, category_id INTEGER NOT NULL REFERENCES categories, list_price NUMERIC(10,2) NOT NULL);
CREATE TABLE customers (customer_id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, country CHAR(2) NOT NULL);
CREATE TABLE orders (order_id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers, status TEXT NOT NULL, ordered_on DATE NOT NULL);
CREATE TABLE order_lines (order_id INTEGER NOT NULL REFERENCES orders, line_no INTEGER NOT NULL, product_id INTEGER NOT NULL REFERENCES products, qty INTEGER NOT NULL, unit_price NUMERIC(10,2) NOT NULL, PRIMARY KEY (order_id, line_no));
