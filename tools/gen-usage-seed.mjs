#!/usr/bin/env node
// Renders examples/lib/tickets-generate.sel into the PostgreSQL seed that
// examples/sql-complex loads, so the rows in the database are exactly the rows
// examples/memory-complex generates in memory -- one source, two routes.
//
//   node tools/gen-usage-seed.mjs            write examples/sql-complex/seed.postgresql.sql
//   node tools/gen-usage-seed.mjs --check    fail if the committed seed is stale
//
// The generator is a SEL program, so rendering it through the JS host is the
// same data every other host builds (tools/check-usage.sh proves it: the
// sql-complex example compares its report over the loaded rows with the report
// over the generated ones).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { evaluate } from '../js/src/sel.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'examples/sql-complex/seed.postgresql.sql');

// Column order and SQL type per table; the generator's records carry the same
// names in the same order, which is checked below rather than assumed.
const TABLES = [
  ['TEAMS', 'teams', [['team_id', 'INTEGER PRIMARY KEY'], ['team', 'TEXT NOT NULL']]],
  ['AGENTS', 'agents', [['agent_id', 'INTEGER PRIMARY KEY'], ['team_id', 'INTEGER NOT NULL'],
    ['agent', 'TEXT NOT NULL']]],
  ['CUSTOMERS', 'customers', [['customer_id', 'INTEGER PRIMARY KEY'], ['customer', 'TEXT NOT NULL'],
    ['plan', 'TEXT NOT NULL']]],
  ['SLA', 'sla', [['plan', 'TEXT NOT NULL'], ['priority', 'TEXT NOT NULL'],
    ['respond_within', 'INTEGER NOT NULL'], ['resolve_within', 'INTEGER NOT NULL']]],
  ['TICKETS', 'tickets', [['ticket_id', 'INTEGER PRIMARY KEY'], ['customer_id', 'INTEGER NOT NULL'],
    ['team_id', 'INTEGER NOT NULL'], ['priority', 'TEXT NOT NULL'], ['subject', 'TEXT NOT NULL'],
    ['opened_at', 'INTEGER NOT NULL'], ['closed_at', 'INTEGER']]],
  ['EVENTS', 'events', [['event_id', 'INTEGER PRIMARY KEY'], ['ticket_id', 'INTEGER NOT NULL'],
    ['seq', 'INTEGER NOT NULL'], ['at', 'INTEGER NOT NULL'], ['kind', 'TEXT NOT NULL'],
    ['actor', 'TEXT NOT NULL']]],
];

const data = evaluate(readFileSync(join(ROOT, 'examples/lib/tickets-generate.sel'), 'utf8'));

function literal(value, type) {
  if (value.isNull()) return 'NULL';
  const text = value.asText();
  return type.startsWith('INTEGER') ? text : `'${text.replaceAll("'", "''")}'`;
}

const out = [
  '-- GENERATED by tools/gen-usage-seed.mjs from examples/lib/tickets-generate.sel -- do not edit.',
  '-- The support desk of examples/sql-complex, for PostgreSQL. Loaded by tools/check-usage.sh.',
  `DROP TABLE IF EXISTS ${TABLES.map(([, t]) => t).reverse().join(', ')};`,
];
for (const [name, table, columns] of TABLES) {
  out.push(`CREATE TABLE ${table} (${columns.map(([c, t]) => `${c} ${t}`).join(', ')});`);
  const rows = [];
  for (const row of data.get(name).values()) {
    const keys = row.keys();
    if (keys.join(',') !== columns.map(([c]) => c).join(',')) {
      throw new Error(`${name}: the generator's fields ${keys.join(',')} are not the table's columns`);
    }
    rows.push(`(${columns.map(([c, t]) => literal(row.get(c), t)).join(', ')})`);
  }
  out.push(`INSERT INTO ${table} VALUES\n  ${rows.join(',\n  ')};`);
}
const text = out.join('\n') + '\n';

if (process.argv.includes('--check')) {
  let have = '';
  try { have = readFileSync(OUT, 'utf8'); } catch { /* missing is stale */ }
  if (have !== text) {
    process.stderr.write('examples/sql-complex/seed.postgresql.sql is stale: run node tools/gen-usage-seed.mjs\n');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, text);
}
